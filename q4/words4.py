"""Words: 4 quaternary digits (little-endian), value 0..4**4-1.

GENERATED by tools/gen_words.py for WORD_QUARTERS = 4. Do not edit by hand;
change the width there and regenerate. to_word/from_word convert at the edges
only; WSEL/WOR/WNOT are the word mux gates; WADD..W_ALU are the word ALU, all
unrolled from the single-digit gates in gates.py (so purity_check still sees
pure gate logic). @ROM memoizes each pure block as a lookup ROM."""

from .gates import (ROM, ROM_BOUNDED, Adr4, EQ, MAX, MIN, NOT, HF_ADDER,
                    HF_SUBTRACT, HF_MULTIPLY)

WORD_QUARTERS = 4

# The instruction frame width (quaternary slots per instruction): one word is
# exactly one frame, which is what makes loading a program a straight copy.
FRAME = 4


# The bus re-derives the same handful of constant port numbers on every access
# (one per device decode line), so this is by far the hottest converter in the
# machine. Memoizing it is the same lookup-ROM trade @ROM makes for the gate
# blocks -- bounded, because unlike a gate block its input is a full 4-digit
# value, so an unbounded table would grow without limit.
@ROM_BOUNDED
def to_word(n):
    return tuple((n // (4 ** k)) % 4 for k in range(WORD_QUARTERS))


def from_word(w):
    return sum(v * (4 ** k) for k, v in enumerate(w))


ZERO_WORD = tuple(0 for _ in range(WORD_QUARTERS))
ONE_WORD = (1,) + tuple(0 for _ in range(WORD_QUARTERS - 1))


def FULL_ADD(a, b, cin):
    c1, s1 = HF_ADDER(a, b)
    c2, s = HF_ADDER(s1, cin)
    return MAX(c1, c2), s


def FULL_SUB(a, b, bin):
    br1, d1 = HF_SUBTRACT(a, b)
    br2, d = HF_SUBTRACT(d1, bin)
    return MAX(br1, br2), d


@ROM
def WSEL(sel, W):
    (w0, w1, w2, w3) = W
    return (MIN(sel, w0), MIN(sel, w1), MIN(sel, w2), MIN(sel, w3))


@ROM
def WOR(A, B):
    (a0, a1, a2, a3) = A
    (b0, b1, b2, b3) = B
    return (MAX(a0, b0), MAX(a1, b1), MAX(a2, b2), MAX(a3, b3))


@ROM
def WNOT(A):
    (a0, a1, a2, a3) = A
    return (NOT(a0), NOT(a1), NOT(a2), NOT(a3))


@ROM
def WADD(A, B):
    (a0, a1, a2, a3) = A
    (b0, b1, b2, b3) = B
    c1, s2 = FULL_ADD(a0, b0, 0)
    c3, s4 = FULL_ADD(a1, b1, c1)
    c5, s6 = FULL_ADD(a2, b2, c3)
    c7, s8 = FULL_ADD(a3, b3, c5)
    return c7, (s2, s4, s6, s8)


@ROM
def WSUB(A, B):
    (a0, a1, a2, a3) = A
    (b0, b1, b2, b3) = B
    b9, d10 = FULL_SUB(a0, b0, 0)
    b11, d12 = FULL_SUB(a1, b1, b9)
    b13, d14 = FULL_SUB(a2, b2, b11)
    b15, d16 = FULL_SUB(a3, b3, b13)
    return b15, (d10, d12, d14, d16)


@ROM
def WGE(A, B):
    (a0, a1, a2, a3) = A
    (b0, b1, b2, b3) = B
    b17, d18 = FULL_SUB(a0, b0, 0)
    b19, d20 = FULL_SUB(a1, b1, b17)
    b21, d22 = FULL_SUB(a2, b2, b19)
    b23, d24 = FULL_SUB(a3, b3, b21)
    g25 = EQ(b23, 0)
    return g25


@ROM
def WMUL(A, B):
    (a0, a1, a2, a3) = A
    (b0, b1, b2, b3) = B
    h26, l27 = HF_MULTIPLY(a0, b0)
    h28, l29 = HF_MULTIPLY(a1, b0)
    h30, l31 = HF_MULTIPLY(a2, b0)
    h32, l33 = HF_MULTIPLY(a3, b0)
    c34, o35 = HF_ADDER(l29, h26)
    _, k36 = HF_ADDER(h28, c34)
    c37, o38 = HF_ADDER(l31, k36)
    _, k39 = HF_ADDER(h30, c37)
    c40, o41 = HF_ADDER(l33, k39)
    mc42, ms43 = FULL_ADD(0, l27, 0)
    mc44, ms45 = FULL_ADD(0, o35, mc42)
    mc46, ms47 = FULL_ADD(0, o38, mc44)
    mc48, ms49 = FULL_ADD(0, o41, mc46)
    h50, l51 = HF_MULTIPLY(a0, b1)
    h52, l53 = HF_MULTIPLY(a1, b1)
    h54, l55 = HF_MULTIPLY(a2, b1)
    c56, o57 = HF_ADDER(l53, h50)
    _, k58 = HF_ADDER(h52, c56)
    c59, o60 = HF_ADDER(l55, k58)
    mc61, ms62 = FULL_ADD(ms45, l51, 0)
    mc63, ms64 = FULL_ADD(ms47, o57, mc61)
    mc65, ms66 = FULL_ADD(ms49, o60, mc63)
    h67, l68 = HF_MULTIPLY(a0, b2)
    h69, l70 = HF_MULTIPLY(a1, b2)
    c71, o72 = HF_ADDER(l70, h67)
    mc73, ms74 = FULL_ADD(ms64, l68, 0)
    mc75, ms76 = FULL_ADD(ms66, o72, mc73)
    h77, l78 = HF_MULTIPLY(a0, b3)
    mc79, ms80 = FULL_ADD(ms76, l78, 0)
    low = (ms43, ms62, ms74, ms80)
    return 0, low


