    r166 = MAX(MAX(MIN(q158, r122), MIN(q159, d133)), MAX(MIN(q160, d143), MIN(q161, d153)))
    b167, d168 = FULL_SUB(a1, b0, 0)
    b169, d170 = FULL_SUB(r162, b1, b167)
