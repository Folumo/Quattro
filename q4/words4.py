@ROM
def WMIN(A, B):
    (a0, a1, a2, a3) = A
    (b0, b1, b2, b3) = B
    b253, d254 = FULL_SUB(a0, b0, 0)
    b255, d256 = FULL_SUB(a1, b1, b253)
    b257, d258 = FULL_SUB(a2, b2, b255)
    b259, d260 = FULL_SUB(a3, b3, b257)
    g261 = EQ(b259, 0)
    gz = EQ(g261, 0)
    return (MAX(MIN(g261, b0), MIN(gz, a0)), MAX(MIN(g261, b1), MIN(gz, a1)), MAX(MIN(g261, b2), MIN(gz, a2)), MAX(MIN(g261, b3), MIN(gz, a3)))


@ROM
def WMAX(A, B):
    (a0, a1, a2, a3) = A
    (b0, b1, b2, b3) = B
    b262, d263 = FULL_SUB(a0, b0, 0)
    b264, d265 = FULL_SUB(a1, b1, b262)
    b266, d267 = FULL_SUB(a2, b2, b264)
    b268, d269 = FULL_SUB(a3, b3, b266)
    g270 = EQ(b268, 0)
    gz = EQ(g270, 0)
    return (MAX(MIN(g270, a0), MIN(gz, b0)), MAX(MIN(g270, a1), MIN(gz, b1)), MAX(MIN(g270, a2), MIN(gz, b2)), MAX(MIN(g270, a3), MIN(gz, b3)))


@ROM
def WMOD(A, B):
    cw, S = WADD(A, B)
    return S


@ROM
def WNZ(A):
    (a0, a1, a2, a3) = A
    return NOT(EQ(MAX(MAX(MAX(a0, a1), a2), a3), 0))


@ROM
def WEQ(A, B):
    (a0, a1, a2, a3) = A
    (b0, b1, b2, b3) = B
    return MIN(MIN(MIN(EQ(a0, b0), EQ(a1, b1)), EQ(a2, b2)), EQ(a3, b3))


@ROM
def W_ALU(InA, InB, Instr0, Instr1):
    """Word ALU: returns (flag_digit, result_word). Width-generic:
    every op runs; the class/sub-op decode lines select the result."""
    Aa, Bb, Cc, Dd = Adr4(Instr0, 3)
    A, B, C, D = Adr4(Instr1, Aa)
    A1, B1, C1, D1 = Adr4(Instr1, Bb)
    Cout, ADD = WADD(InA, InB)
    Borrow, SUBr = WSUB(InA, InB)
    Mov, MULr = WMUL(InA, InB)
    Rem, QUOT = WDIV(InA, InB)
    arith = WOR(WOR(WSEL(A, ADD), WSEL(B, SUBr)),
                WOR(WSEL(C, MULr), WSEL(D, QUOT)))
    (rm0, rm1, rm2, rm3) = Rem
    Xdiv = MIN(1, MAX(MAX(MAX(rm0, rm1), rm2), rm3))
    flag = MAX(MAX(MIN(A, Cout), MIN(B, Borrow)), MAX(MIN(C, Mov), MIN(D, Xdiv)))
    logic = WOR(WOR(WSEL(A1, WMIN(InA, InB)), WSEL(B1, WMAX(InA, InB))),
                WOR(WSEL(C1, WMOD(InA, InB)), WSEL(D1, WNOT(InA))))
    return flag, WOR(arith, logic)
